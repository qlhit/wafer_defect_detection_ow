#!/usr/bin/env python3
"""Composition-conditioned unknown-component scoring for a trained Teacher.

For a sample such as C+L+S, RDP first predicts the known projection C+L.  The
sample responses are then compared with the known-validation reference bank
for C+L instead of one global known distribution.

The script trains nothing, writes nothing, and prints one JSON.  It reports:

1. ``rdp_predicted``: deployable composition selection from RDP predictions.
2. ``oracle_projection``: diagnostic upper bound using the true label after
   removing the held-out atomic class (S by default).

Known-validation scores used for threshold calibration are generated by
stratified cross-fitting, so known_test is not used to choose the threshold.
"""

from __future__ import annotations

import argparse
import json
from collections import Counter
from typing import Dict, Iterable, Mapping, Optional, Sequence, Tuple

import numpy as np
import torch
from sklearn.metrics import average_precision_score, roc_auc_score, roc_curve

from evaluate_teacher_multiscore import (
    MORPHOLOGY_NAMES,
    collect_raw_responses,
    deterministic_subset,
    fit_reference,
    materialize_scores,
)
from train_component_conditioned_teacher import (
    FULL_CLASSES,
    FlowTeacherUNet,
    ImageConditionAdapter,
    forward_rdp_features,
    load_arrays,
    load_frozen_rdp,
    make_loader,
    make_open_set_split,
    set_seed,
    torch_load,
)


RESPONSE_NAMES: Tuple[str, ...] = (
    "velocity_mse",
    "velocity_die_mse",
    "reconstruction_pixel_mse",
    "reconstruction_dice_loss",
    "reconstruction_pattern_cosine",
    "rdp_feature_diag_mahalanobis",
    "morphology_robust_deviation",
)

FUSION_DEFINITIONS: Mapping[str, Tuple[str, ...]] = {
    "generative_fusion": (
        "velocity_die_mse",
        "reconstruction_pixel_mse",
    ),
    "reference_fusion": (
        "rdp_feature_diag_mahalanobis",
        "morphology_robust_deviation",
    ),
    "equal_all_fusion": (
        "velocity_die_mse",
        "reconstruction_pixel_mse",
        "reconstruction_pattern_cosine",
        "rdp_feature_diag_mahalanobis",
        "morphology_robust_deviation",
    ),
}


