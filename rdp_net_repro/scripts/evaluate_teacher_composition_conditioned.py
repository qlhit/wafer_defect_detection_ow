def response_only(raw: Mapping[str, np.ndarray]) -> Dict[str, np.ndarray]:
    return {
        key: value
        for key, value in raw.items()
        if key in (
            "velocity_mse",
            "velocity_die_mse",
            "reconstruction_pixel_mse",
            "reconstruction_dice_loss",
            "reconstruction_pattern_cosine",
            "rdp_features",
            "morphology_descriptors",
        )
    }


def slice_raw(
    raw: Mapping[str, np.ndarray], indices: Sequence[int]
) -> Dict[str, np.ndarray]:
    idx = np.asarray(indices, dtype=np.int64)
    return {key: value[idx] for key, value in response_only(raw).items()}


@torch.inference_mode()
def collect_metadata(loader, rdp_model, device: torch.device) -> Dict[str, np.ndarray]:
    labels, probabilities = [], []
    for x_raw, y_full in loader:
        x_raw = x_raw.to(device, non_blocking=True)
        logits, _ = forward_rdp_features(
            rdp_model, x_raw.unsqueeze(1).float()
        )
        labels.append(y_full.numpy())
        probabilities.append(torch.sigmoid(logits).cpu().numpy())
    return {
        "labels": np.concatenate(labels, axis=0),
        "rdp_probabilities": np.concatenate(probabilities, axis=0),
    }


def active_indices(unknown_idx: int) -> np.ndarray:
    return np.asarray(
        [index for index in range(len(FULL_CLASSES)) if index != unknown_idx],
        dtype=np.int64,
    )


def encode_compositions(
    values: np.ndarray, unknown_idx: int, threshold: float
) -> np.ndarray:
    active = active_indices(unknown_idx)
    bits = (values[:, active] >= threshold).astype(np.int64)
    weights = 1 << np.arange(len(active), dtype=np.int64)
    return bits @ weights


def composition_name(code: int, unknown_idx: int) -> str:
    active = active_indices(unknown_idx)
    names = [
        FULL_CLASSES[original]
        for bit, original in enumerate(active)
        if int(code) & (1 << bit)
    ]
    return "+".join(names) if names else "EMPTY"


def fit_one_reference(raw: Mapping[str, np.ndarray], indices: np.ndarray):
    subset = slice_raw(raw, indices)
    reference = fit_reference(subset)
    reference["calibration_features"] = subset["rdp_features"]
    reference["calibration_morphology"] = subset["morphology_descriptors"]
    return reference


def fit_reference_bank(
    raw: Mapping[str, np.ndarray],
    truth_codes: np.ndarray,
    min_group_samples: int,
) -> Dict[str, object]:
    all_indices = np.arange(len(truth_codes), dtype=np.int64)
    counts = Counter(int(code) for code in truth_codes)
    groups = {}
    for code, count in counts.items():
        if count >= min_group_samples:
            indices = np.flatnonzero(truth_codes == code)
            groups[int(code)] = fit_one_reference(raw, indices)
    return {
        "global": fit_one_reference(raw, all_indices),
        "groups": groups,
        "counts": dict(counts),
    }


def resolve_reference_code(
    query_code: int, bank: Mapping[str, object]
) -> Tuple[Optional[int], str]:
    groups = bank["groups"]
    if query_code in groups:
        return int(query_code), "exact"
    # S-only has an empty known projection.  There is no defect-free template
    # in this protocol, so it must use the global fallback explicitly.
    if int(query_code) == 0:
        return None, "global_empty"
    if not groups:
        return None, "global_no_group"

    counts = bank["counts"]
    ranked = sorted(
        groups,
        key=lambda code: (
            int(int(code) ^ int(query_code)).bit_count(),
            -int(counts.get(int(code), 0)),
            int(code),
        ),
    )
    return int(ranked[0]), "nearest_hamming"


def score_with_bank(
    raw: Mapping[str, np.ndarray],
    query_codes: np.ndarray,
    bank: Mapping[str, object],
) -> Tuple[Dict[str, np.ndarray], Dict[str, int]]:
    output = {
        name: np.empty(len(query_codes), dtype=np.float64)
        for name in RESPONSE_NAMES
    }
    assignments: Dict[Optional[int], list[int]] = {}
    statuses: Counter[str] = Counter()
    for index, query_code in enumerate(query_codes):
        reference_code, status = resolve_reference_code(int(query_code), bank)
        assignments.setdefault(reference_code, []).append(index)
        statuses[status] += 1

    for reference_code, indices_list in assignments.items():
        indices = np.asarray(indices_list, dtype=np.int64)
        reference = (
            bank["global"]
            if reference_code is None
            else bank["groups"][reference_code]
        )
        _, calibrated = materialize_scores(slice_raw(raw, indices), reference)
        for name in RESPONSE_NAMES:
            output[name][indices] = calibrated[name]
    return output, dict(statuses)


def stratified_folds(codes: np.ndarray, folds: int, seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    assignment = np.empty(len(codes), dtype=np.int64)
    for code in np.unique(codes):
        indices = np.flatnonzero(codes == code)
        rng.shuffle(indices)
        assignment[indices] = np.arange(len(indices)) % folds
    return assignment


def crossfit_calibration_scores(
    raw: Mapping[str, np.ndarray],
    truth_codes: np.ndarray,
    query_codes: np.ndarray,
    min_group_samples: int,
    folds: int,
    seed: int,
) -> Tuple[Dict[str, np.ndarray], Dict[str, int]]:
    fold_ids = stratified_folds(truth_codes, folds, seed)
    output = {
        name: np.empty(len(truth_codes), dtype=np.float64)
        for name in RESPONSE_NAMES
    }
    total_statuses: Counter[str] = Counter()
    for fold in range(folds):
        fit_indices = np.flatnonzero(fold_ids != fold)
        score_indices = np.flatnonzero(fold_ids == fold)
        bank = fit_reference_bank(
            slice_raw(raw, fit_indices),
            truth_codes[fit_indices],
            min_group_samples,
        )
        fold_scores, statuses = score_with_bank(
            slice_raw(raw, score_indices), query_codes[score_indices], bank
        )
        for name in RESPONSE_NAMES:
            output[name][score_indices] = fold_scores[name]
        total_statuses.update(statuses)
    return output, dict(total_statuses)


def fpr_at_tpr95(labels: np.ndarray, scores: np.ndarray) -> float:
    fpr, tpr, _ = roc_curve(labels, scores)
    candidates = np.flatnonzero(tpr >= 0.95)
    return float(fpr[candidates[0]]) if len(candidates) else 1.0


def evaluate_at_calibrated_threshold(
    calibration_scores: np.ndarray,
    known_scores: np.ndarray,
    unknown_scores: np.ndarray,
    known_reject_rate: float,
) -> Dict[str, float]:
    labels = np.concatenate(
        [
            np.zeros(len(known_scores), dtype=np.int64),
            np.ones(len(unknown_scores), dtype=np.int64),
        ]
    )
    scores = np.concatenate([known_scores, unknown_scores])
    threshold = float(
        np.quantile(calibration_scores, 1.0 - known_reject_rate)
    )
    known_reject = float(np.mean(known_scores > threshold))
    unknown_recall = float(np.mean(unknown_scores > threshold))
    return {
        "auroc": float(roc_auc_score(labels, scores)),
        "aupr": float(average_precision_score(labels, scores)),
        "fpr95": fpr_at_tpr95(labels, scores),
        "threshold_from_known_validation": threshold,
        "known_test_reject_rate": known_reject,
        "unknown_recall_at_threshold": unknown_recall,
        "balanced_accuracy_at_threshold": float(
            0.5 * ((1.0 - known_reject) + unknown_recall)
        ),
        "known_mean": float(np.mean(known_scores)),
        "unknown_mean": float(np.mean(unknown_scores)),
    }


def resolution_rates(statuses: Mapping[str, int]) -> Dict[str, float]:
    total = max(1, sum(statuses.values()))
    return {key: value / total for key, value in sorted(statuses.items())}


def make_fusions(
    scores: Mapping[str, np.ndarray], clip: float
) -> Dict[str, np.ndarray]:
    output = {}
    for fusion_name, components in FUSION_DEFINITIONS.items():
        matrix = np.column_stack(
            [np.clip(scores[name], 0.0, clip) for name in components]
        )
        output[fusion_name] = matrix.mean(axis=1)
    return output


def metrics_for_scores(
    calibration: Mapping[str, np.ndarray],
    known: Mapping[str, np.ndarray],
    unknown: Mapping[str, np.ndarray],
    unknown_mask: np.ndarray,
    reject_rate: float,
) -> Dict[str, Dict[str, float]]:
    return {
        name: evaluate_at_calibrated_threshold(
            calibration[name], known[name], values[unknown_mask], reject_rate
        )
        for name, values in unknown.items()
    }


def run_protocol(
    calibration_raw: Mapping[str, np.ndarray],
    known_raw: Mapping[str, np.ndarray],
    unknown_raw: Mapping[str, np.ndarray],
    calibration_truth_codes: np.ndarray,
    calibration_query_codes: np.ndarray,
    known_query_codes: np.ndarray,
    unknown_query_codes: np.ndarray,
    unknown_is_pure: np.ndarray,
    min_group_samples: int,
    crossfit_folds: int,
    fusion_clip: float,
    reject_rate: float,
    unknown_idx: int,
    seed: int,
) -> Dict[str, object]:
    calibration_scores, calibration_status = crossfit_calibration_scores(
        calibration_raw,
        calibration_truth_codes,
        calibration_query_codes,
        min_group_samples,
        crossfit_folds,
        seed,
    )
    bank = fit_reference_bank(
        calibration_raw, calibration_truth_codes, min_group_samples
    )
    known_scores, known_status = score_with_bank(
        known_raw, known_query_codes, bank
    )
    unknown_scores, unknown_status = score_with_bank(
        unknown_raw, unknown_query_codes, bank
    )

    calibration_all = {
        **calibration_scores,
        **make_fusions(calibration_scores, fusion_clip),
    }
    known_all = {**known_scores, **make_fusions(known_scores, fusion_clip)}
    unknown_all = {**unknown_scores, **make_fusions(unknown_scores, fusion_clip)}
    masks = {
        "all_unknown": np.ones(len(unknown_is_pure), dtype=bool),
        "pure_unknown_only": unknown_is_pure,
        "mixed_known_plus_unknown": ~unknown_is_pure,
    }
    subset_metrics = {}
    for subset_name, mask in masks.items():
        if int(mask.sum()) == 0:
            continue
        subset_metrics[subset_name] = {
            "samples": int(mask.sum()),
            "scores": metrics_for_scores(
                calibration_all,
                known_all,
                unknown_all,
                mask,
                reject_rate,
            ),
        }
    group_counts = {
        composition_name(int(code), unknown_idx=unknown_idx): int(count)
        for code, count in sorted(bank["counts"].items())
    }
    eligible_groups = [
        composition_name(int(code), unknown_idx=unknown_idx)
        for code in sorted(bank["groups"])
    ]
    return {
        "reference_group_counts": group_counts,
        "eligible_reference_groups": eligible_groups,
        "reference_resolution_rates": {
            "known_validation_crossfit": resolution_rates(calibration_status),
            "known_test": resolution_rates(known_status),
            "unknown_test": resolution_rates(unknown_status),
        },
        "evaluation": subset_metrics,
    }


def exact_composition_accuracy(predicted: np.ndarray, truth: np.ndarray) -> float:
    return float(np.mean(predicted == truth))


def main() -> None:
    args = parse_args()
    if args.num_t < 1 or args.ode_steps < 1:
        raise ValueError("--num-t and --ode-steps must be positive")
    if not 0.0 < args.t_min <= args.t_max < 1.0:
        raise ValueError("Require 0 < t-min <= t-max < 1")
    if args.min_group_samples < 2:
        raise ValueError("--min-group-samples must be at least 2")
    if args.crossfit_folds < 2:
        raise ValueError("--crossfit-folds must be at least 2")
    set_seed(args.seed)
    device = torch.device("cuda:0" if torch.cuda.is_available() else "cpu")
    amp_enabled = bool(args.amp and device.type == "cuda")

    checkpoint = torch_load(args.teacher_checkpoint, map_location="cpu")
    configuration = checkpoint["configuration"]
    if configuration["unknown_class"] != args.unknown_class:
        raise ValueError(
            f"Teacher holds out {configuration['unknown_class']}, not "
            f"{args.unknown_class}"
        )
    unknown_idx = FULL_CLASSES.index(args.unknown_class)
    image_size = int(configuration["image_size"])
    condition_dim = int(configuration["condition_dim"])
    rdp_checkpoint = args.rdp_checkpoint or configuration["rdp_checkpoint"]

    teacher = FlowTeacherUNet(condition_dim).to(device).eval()
    image_adapter = ImageConditionAdapter(512, condition_dim).to(device).eval()
    teacher.load_state_dict(checkpoint["teacher_state_dict"], strict=True)
    image_adapter.load_state_dict(
        checkpoint["image_adapter_state_dict"], strict=True
    )
    rdp_model = load_frozen_rdp(rdp_checkpoint, args.unknown_class, device)

    x, y = load_arrays(args.data)
    raw_scale = 2.0 if float(x.max().item()) > 1.0 else 1.0
    split = make_open_set_split(
        y,
        unknown_idx,
        args.known_train_ratio,
        args.known_val_ratio,
        args.seed,
    )
    selected = {
        "calibration": deterministic_subset(
            split["known_val"], args.calibration_n, args.seed + 1
        ),
        "known_test": deterministic_subset(
            split["known_test"], args.known_eval_n, args.seed + 2
        ),
        "unknown_test": deterministic_subset(
            split["unknown_test"], args.unknown_eval_n, args.seed + 3
        ),
    }
    loaders = {
        name: make_loader(
            x,
            y,
            indices,
            args.batch_size,
            False,
            args.num_workers,
            device.type == "cuda",
        )
        for name, indices in selected.items()
    }
    t_values = np.linspace(args.t_min, args.t_max, args.num_t)
    raw, metadata = {}, {}
    for name, loader in loaders.items():
        print(f"scoring {name}", flush=True)
        raw[name] = collect_raw_responses(
            loader,
            teacher,
            image_adapter,
            rdp_model,
            device,
            image_size,
            raw_scale,
            t_values,
            args.ode_steps,
            amp_enabled,
            seed=args.seed + 30000,
        )
        metadata[name] = collect_metadata(loader, rdp_model, device)

    truth_codes = {
        name: encode_compositions(values["labels"], unknown_idx, 0.5)
        for name, values in metadata.items()
    }
    predicted_codes = {
        name: encode_compositions(
            values["rdp_probabilities"], unknown_idx, args.rdp_threshold
        )
        for name, values in metadata.items()
    }
    unknown_known_count = (
        metadata["unknown_test"]["labels"][:, active_indices(unknown_idx)]
        >= 0.5
    ).sum(axis=1)
    unknown_is_pure = unknown_known_count == 0

    common = dict(
        calibration_raw=raw["calibration"],
        known_raw=raw["known_test"],
        unknown_raw=raw["unknown_test"],
        calibration_truth_codes=truth_codes["calibration"],
        unknown_is_pure=unknown_is_pure,
        min_group_samples=args.min_group_samples,
        crossfit_folds=args.crossfit_folds,
        fusion_clip=args.fusion_clip,
        reject_rate=args.known_reject_rate,
        unknown_idx=unknown_idx,
    )
    protocols = {
        "rdp_predicted": run_protocol(
            **common,
            calibration_query_codes=predicted_codes["calibration"],
            known_query_codes=predicted_codes["known_test"],
            unknown_query_codes=predicted_codes["unknown_test"],
            seed=args.seed + 40000,
        ),
        "oracle_projection": run_protocol(
            **common,
            calibration_query_codes=truth_codes["calibration"],
            known_query_codes=truth_codes["known_test"],
            unknown_query_codes=truth_codes["unknown_test"],
            seed=args.seed + 50000,
        ),
    }

    result = {
        "configuration": {
            "unknown_class": args.unknown_class,
            "teacher_checkpoint": args.teacher_checkpoint,
            "rdp_checkpoint": rdp_checkpoint,
            "device": str(device),
            "calibration_samples": len(selected["calibration"]),
            "known_samples": len(selected["known_test"]),
            "unknown_samples": len(selected["unknown_test"]),
            "pure_unknown_samples": int(unknown_is_pure.sum()),
            "mixed_known_plus_unknown_samples": int((~unknown_is_pure).sum()),
            "rdp_threshold": args.rdp_threshold,
            "min_group_samples": args.min_group_samples,
            "crossfit_folds": args.crossfit_folds,
            "known_reject_rate_target": args.known_reject_rate,
            "num_t": args.num_t,
            "ode_steps": args.ode_steps,
            "t_values": t_values.tolist(),
            "fusion_clip": args.fusion_clip,
            "fusion_definitions": {
                key: list(value) for key, value in FUSION_DEFINITIONS.items()
            },
        },
        "rdp_known_projection_exact_match": {
            "known_validation": exact_composition_accuracy(
                predicted_codes["calibration"], truth_codes["calibration"]
            ),
            "known_test": exact_composition_accuracy(
                predicted_codes["known_test"], truth_codes["known_test"]
            ),
            "unknown_test": exact_composition_accuracy(
                predicted_codes["unknown_test"], truth_codes["unknown_test"]
            ),
        },
        "protocols": protocols,
        "morphology_descriptor_order": list(MORPHOLOGY_NAMES),
        "interpretation": {
            "oracle_high_rdp_low": "RDP composition selection is the bottleneck",
            "oracle_and_rdp_high": "composition-conditioned scoring is viable",
            "oracle_still_low": "Teacher responses do not expose the held-out component",
            "global_empty": "pure held-out samples have no defect-free reference template",
            "target_labels": "unknown labels are used only for evaluation and oracle diagnosis",
        },
    }
    print(json.dumps(result, ensure_ascii=False, indent=2))


if __name__ == "__main__":
    main()
